constexpr FontGlyph tinyhex_make_glyph(uint32_t offset, uint16_t advance = 4)
{
    return FontGlyph{offset, 3, 5, 0, 0, advance};
}

constexpr FontGlyph tinyhex_placeholder_glyph(uint16_t advance = 4)
{
    return FontGlyph{0, 3, 5, 0, 0, advance};
}

constexpr FontGlyph tinyhex_space_glyph()
{
    return FontGlyph{0, 0, 0, 0, 0, 2};
}

